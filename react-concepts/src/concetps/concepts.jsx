// concepts 
// Basic Concepts  
// 1. JSX (JavaScript XML) – Writing HTML-like syntax in JavaScript.  
// 2. Components – Functional and Class components.  
// 3. Props – Passing data to child components.  
// 4. State Management – Handling local state using `useState`.  
// 5. Event Handling – Handling user interactions (e.g., `onClick`, `onChange`).  
// 6. Conditional Rendering – Rendering content conditionally (`if-else`, `ternary operator`).  
// 7. Lists and Keys – Rendering lists using `map` and assigning unique keys.  
// 8. Forms – Controlled vs. Uncontrolled components for handling form inputs.  

// Intermediate Concepts  
// 1. Hooks:  
//    - `useState` for state.  
//    - `useEffect` for side effects.  
//    - `useContext` for avoiding prop drilling.  
// 2. Context API – Sharing global state across components without Redux.  
// 3. React Router – Routing in React applications (`BrowserRouter`, `Routes`, `Link`).  
// 4. Refs – Using `useRef` for accessing DOM elements or persisting values.  
// 5. Fragments – Grouping elements without adding extra DOM nodes.  
// 6. Error Boundaries – Catching JavaScript errors in components (Class-based).  
// 7. Higher-Order Components (HOCs) – Enhancing components by wrapping them.  
// 8. Portals – Rendering children outside the DOM hierarchy of the parent component.  

// Advanced Concepts  
// 1. Redux / Redux Toolkit – Centralized state management.  
// 2. Custom Hooks – Creating reusable logic.  
// 3. Lazy Loading & Code Splitting – Improving performance for large apps.  
// 4. Memoization:  
//    - `React.memo` – Prevent unnecessary re-renders.  
//    - `useMemo` – Cache expensive calculations.  
//    - `useCallback` – Memoize functions.  
// 5. Error Handling – Custom error boundaries for functional components.  
// 6. API Handling – Using Axios, Fetch, or Redux Thunk/RTK Query for API calls.  
// 7. Performance Optimization – Techniques like virtualizing lists and avoiding reconciliation.  
// 8. Testing – Writing unit tests using `Jest` and `React Testing Library`.  
// 9. Reusable Components – Designing modular and reusable components for large apps.  
// 10. Dynamic Styling – Applying styles dynamically using CSS Modules, `styled-components`, or Tailwind CSS.  

// Deployment Concepts  
// 1. Building React App – `npm run build` creates optimized production files.  
// 2. Hosting Options – Using platforms like Vercel, Netlify, AWS, or Firebase.  
// 3. Environment Variables – Securely handling sensitive configurations.  

// Real-Time Project Concepts  
// 1. State Management – Global state management with Context API or Redux.  
// 2. Dynamic Routing – Nested routes and query parameters with React Router.  
// 3. Authentication – Token-based authentication and route guards.  
// 4. Pagination & Infinite Scrolling – Handling large datasets efficiently.  
// 5. Error Monitoring – Implementing logging libraries like Sentry.  
// 6. Accessibility – Ensuring app compliance with WCAG standards.  
// 7. Performance Metrics – Monitoring and optimizing app performance (Lighthouse, React DevTools).  
